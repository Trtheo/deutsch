// Writes frontend/src/lessonCatalog.js from backend/content (card data only, no exam answers).
// Run after adding or renaming lessons: npm run catalog
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '../../frontend/src/lessonCatalog.js');

function renderCatalog(lessons) {
  // Import only the icons in use, so the bundle doesn't pull in all of lucide-react
  const icons = [...new Set(lessons.map(l => l.meta.icon))].sort();
  const rows = lessons.map(l => {
    const data = JSON.stringify({
      slug: l.slug, title: l.title, titleDe: l.titleDe, sub: l.meta.sub,
      level: l.level, category: l.category, group: l.meta.group,
    });
    return `  { ${data.slice(1, -1)}, Icon: ${l.meta.icon} },`;
  });
  return `// Generated by backend/scripts/build-catalog.js from backend/content. Do not edit by hand.
import { ${icons.join(', ')} } from 'lucide-react';

const LESSON_CATALOG = [
${rows.join('\n')}
];

export default LESSON_CATALOG;
`;
}

module.exports = { renderCatalog, OUT };

if (require.main === module) {
  const lessons = require('../content');
  const { validate } = require('../content/validate');
  const errors = validate(lessons);
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  fs.writeFileSync(OUT, renderCatalog(lessons));
  console.log(`✔ Wrote ${lessons.length} lessons to ${path.relative(process.cwd(), OUT)}`);
}
